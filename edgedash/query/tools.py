# Tool 5: trend
# ---------------------------------------------------------------------------

@tool(
    description=(
        "Returns how the opportunity cost of each skill gap has changed over the last "
        "N weeks, comparing the earliest and latest snapshots in that window. "
        "Use when the question is about change over time, whether gaps are growing or "
        "shrinking, or trend. Do NOT use for current gaps or listing details."
    ),
    params={
        "weeks": {
            "type": "integer",
            "description": "Number of weeks to look back. Clamped to 1–12.",
            "default": 3,
        }
    },
)
def trend(config: Config, weeks: int = 3) -> dict[str, Any]:
    weeks = _clamp_int(weeks, 1, 12, 3)

    n_snapshots = storage.get_snapshot_count(_db(config))
    if n_snapshots < 2:
        return {
            "rows":    [],
            "summary": f"Only {n_snapshots} snapshot(s) available. "
                       f"Trend requires at least 2. Run more cycles.",
        }

    _, e_at, early_rows = storage.get_gap_snapshot_by_position(_db(config), "earliest")
    _, l_at, late_rows  = storage.get_gap_snapshot_by_position(_db(config), "latest")

    early_map = {r["skill"]: r["opportunity_cost"] for r in early_rows}
    late_top10 = late_rows[:10]

    rows = []
    for g in late_top10:
        skill       = g["skill"]
        latest_cost = g["opportunity_cost"]
        early_cost  = early_map.get(skill)
        change      = (latest_cost - early_cost) if early_cost is not None else None
        pct         = (change / early_cost * 100) if (change is not None and early_cost) else None
        rows.append({
            "skill":        skill,
            "earliest":     round(early_cost, 2) if early_cost is not None else None,
            "latest":       round(latest_cost, 2),
            "change":       round(change, 2) if change is not None else None,
            "change_pct":   round(pct, 1) if pct is not None else None,
            "is_new":       early_cost is None,
        })

    e_ts = e_at[:19].replace("T", " ")
    l_ts = l_at[:19].replace("T", " ")
    summary = (
        f"Trend for top 10 gaps. "
        f"Comparing earliest snapshot ({e_ts}) to latest ({l_ts}). "
        f"{n_snapshots} total snapshots in DB."
    )
    return {"rows": rows, "summary": summary}


