"""
query/tools.py — parameterised read-only query functions.

Rules:
  40. No SQL is ever generated by a model. These are the ONLY queries.
  41. Every parameter is validated and clamped before use.
  46. All reads from the last passing cycle only.

The @tool decorator registers each function in TOOLS with its name,
description, and parameter spec. The description is what the router
model sees — it must be unambiguous about when the tool applies.
"""

from __future__ import annotations

import json
from datetime import datetime, timedelta, timezone
from typing import Any, Callable

import edgedash.storage as storage
from edgedash.config import Config
from edgedash.skills import canonical

# ---------------------------------------------------------------------------
# Tool registry and decorator
# ---------------------------------------------------------------------------

TOOLS: dict[str, dict[str, Any]] = {}


def tool(
    description: str,
    params: dict[str, Any],
) -> Callable:
    """
    Register a query function in TOOLS.

    description — what the router model sees. Must be specific enough that
                  the router cannot confuse this tool with another.
    params      — JSON-schema-style spec: {param_name: {type, description, default}}.
                  Used by the router to know what arguments to supply.
    """
    def decorator(fn: Callable) -> Callable:
        TOOLS[fn.__name__] = {
            "fn":          fn,
            "description": description,
            "params":      params,
        }
        return fn
    return decorator


# ---------------------------------------------------------------------------
# Parameter validation helpers
# ---------------------------------------------------------------------------

def _clamp_int(value: Any, lo: int, hi: int, default: int) -> int:
    """Parse and clamp an integer parameter. Returns default on bad input."""
    try:
        v = int(value)
    except (TypeError, ValueError):
        return default
    return max(lo, min(hi, v))


def _safe_skill(value: Any, aliases: dict[str, str]) -> str:
    """Canonicalise and strip a skill string from untrusted model input."""
    if not isinstance(value, str):
        return ""
    return canonical(value, aliases)


def _db(config: Config) -> str:
    return config.db_path


# ---------------------------------------------------------------------------
# Tool 1: companies_hiring
# ---------------------------------------------------------------------------

@tool(
    description=(
        "Returns the companies that have posted job listings in the last N days, "
        "with their listing count and best fit score. Use when the question is about "
        "which companies are actively hiring or how many listings a company has. "
        "Do NOT use for questions about specific jobs, skills, or score rankings."
    ),
    params={
        "days": {
            "type": "integer",
            "description": "Number of days to look back. Clamped to 1–90.",
            "default": 7,
        }
    },
)
def companies_hiring(config: Config, days: int = 7) -> dict[str, Any]:
    days = _clamp_int(days, 1, 90, 7)
    cutoff = (datetime.now(timezone.utc) - timedelta(days=days)).isoformat()

    # Read all scored listings through storage (rule 2), filter in Python
    all_listings = storage.get_listings(_db(config), limit=1000, min_score=0)
    recent = [
        r for r in all_listings
        if (r.get("fetched_at") or "") >= cutoff
    ]

    # Aggregate by company
    companies: dict[str, dict[str, Any]] = {}
    for r in recent:
        co = r.get("company") or "Unknown"
        if co not in companies:
            companies[co] = {"company": co, "listing_count": 0, "best_score": 0}
        companies[co]["listing_count"] += 1
        companies[co]["best_score"] = max(
            companies[co]["best_score"], r.get("fit_score") or 0
        )

    rows = sorted(companies.values(), key=lambda x: -x["listing_count"])
    summary = f"{len(recent)} scored listings from the last {days} day(s), {len(rows)} companies."
    return {"rows": rows, "summary": summary}


