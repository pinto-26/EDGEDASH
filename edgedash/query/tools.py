@tool(
    description=(
        "Returns a summary of how many listings are in the database: total, scored, "
        "unscored, and the date of the newest listing. Use when the question is about "
        "how many jobs were found, database size, or coverage. "
        "Do NOT use for scores, companies, gaps, or trends."
    ),
    params={},
)
def listing_count(config: Config) -> dict[str, Any]:
    path = _db(config)

    all_listings    = storage.get_listings(path, limit=10000, min_score=0)
    total_scored    = len(all_listings)
    total_unscored  = storage.count_unscored(path)
    total           = total_scored + total_unscored
    newest_fetch    = storage.last_fetch_time(path)

    rows = [{
        "total_listings":   total,
        "scored":           total_scored,
        "unscored":         total_unscored,
        "newest_fetch_at":  newest_fetch,
    }]
    summary = (
        f"{total} listings total: {total_scored} scored, "
        f"{total_unscored} unscored. Newest: {newest_fetch or 'none'}."
    )
    return {"rows": rows, "summary": summary}


