# Tool 7: skill_demand
# ---------------------------------------------------------------------------

@tool(
    description=(
        "Returns how often one specific named skill appears in job listings — "
        "as a required skill vs nice-to-have, across all extractions in the database. "
        "Use when the question is about how in-demand one skill is, how often it appears, "
        "or whether it is required vs preferred. "
        "Requires a skill name. Do NOT use for gaps, scores, or trends."
    ),
    params={
        "skill": {
            "type": "string",
            "description": "The skill name to look up (e.g. 'python', 'tableau').",
            "default": "",
        }
    },
)
def skill_demand(config: Config, skill: str = "") -> dict[str, Any]:
    canon_skill = _safe_skill(skill, config.skill_aliases)
    if not canon_skill:
        return {"rows": [], "summary": "No skill specified."}

    extractions = storage.get_scored_listings_with_extractions(_db(config))

    required_count   = 0
    nice_count       = 0
    total_extractions = len(extractions)

    for e in extractions:
        facts    = e.get("extracted") or {}
        req_set  = {canonical(s, config.skill_aliases) for s in (facts.get("required_skills") or [])}
        nice_set = {canonical(s, config.skill_aliases) for s in (facts.get("nice_to_have") or [])}
        if canon_skill in req_set:
            required_count += 1
        elif canon_skill in nice_set:
            nice_count += 1

    total_appearances = required_count + nice_count
    if total_extractions > 0:
        req_pct  = round(required_count  / total_extractions * 100, 1)
        nice_pct = round(nice_count      / total_extractions * 100, 1)
    else:
        req_pct = nice_pct = 0.0

    rows = [{
        "skill":                 canon_skill,
        "required_in":           required_count,
        "nice_to_have_in":       nice_count,
        "total_appearances":     total_appearances,
        "required_pct":          req_pct,
        "nice_to_have_pct":      nice_pct,
        "total_extractions":     total_extractions,
    }]

    if total_appearances == 0:
        summary = (
            f"Skill '{canon_skill}' not found in any of {total_extractions} "
            f"extraction(s). It may not appear in your current listings."
        )
    else:
        summary = (
            f"'{canon_skill}' appears in {total_appearances}/{total_extractions} "
            f"extraction(s): {required_count} required ({req_pct}%), "
            f"{nice_count} nice-to-have ({nice_pct}%)."
        )
    return {"rows": rows, "summary": summary}
