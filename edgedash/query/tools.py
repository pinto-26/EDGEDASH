# Tool 2: best_matches
# ---------------------------------------------------------------------------

@tool(
    description=(
        "Returns the highest-scoring job listings with their score, title, company, "
        "location, and fit reason. Use when the question is about the best or "
        "highest-scored jobs, or which jobs to apply to. "
        "Do NOT use for company counts, skill gaps, or trend questions."
    ),
    params={
        "n": {
            "type": "integer",
            "description": "Number of top listings to return. Clamped to 1–25.",
            "default": 10,
        }
    },
)
def best_matches(config: Config, n: int = 10) -> dict[str, Any]:
    n = _clamp_int(n, 1, 25, 10)
    rows = storage.get_listings(_db(config), limit=n, min_score=0)
    # get_listings already returns newest-first; re-sort by score descending
    rows = sorted(rows, key=lambda r: -(r.get("fit_score") or 0))[:n]
    result = [
        {
            "score":   r.get("fit_score"),
            "title":   r.get("title"),
            "company": r.get("company"),
            "location":r.get("location"),
            "reason":  r.get("fit_reason"),
            "url":     r.get("url"),
        }
        for r in rows
    ]
    summary = f"Top {len(result)} scored listing(s) out of all scored listings."
    return {"rows": result, "summary": summary}


