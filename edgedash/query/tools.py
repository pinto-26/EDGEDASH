# Tool 4: gap_detail  (rule 26 drill-down)
# ---------------------------------------------------------------------------

@tool(
    description=(
        "Returns the specific listings blocked by one named skill gap — title, company, "
        "score, and location. Use when the question asks WHY a skill is a gap, which "
        "specific jobs require it, or asks to drill into one gap. "
        "Requires a skill name. Do NOT use for ranking all gaps or general gap summaries."
    ),
    params={
        "skill": {
            "type": "string",
            "description": "The skill name to drill into (e.g. 'kubernetes', 'spark').",
            "default": "",
        }
    },
)
def gap_detail(config: Config, skill: str = "") -> dict[str, Any]:
    canon_skill = _safe_skill(skill, config.skill_aliases)
    if not canon_skill:
        return {"rows": [], "summary": "No skill specified."}

    # Find the gap entry to get example_ids
    all_gaps = storage.get_latest_gap_snapshot(_db(config))
    gap_entry = next(
        (g for g in all_gaps if g.get("skill") == canon_skill), None
    )

    if gap_entry is None:
        # Also try case-insensitive partial match
        gap_entry = next(
            (g for g in all_gaps if canon_skill in (g.get("skill") or "")), None
        )

    if gap_entry is None:
        return {
            "rows":    [],
            "summary": f"Skill '{canon_skill}' not found in gap snapshot. "
                       f"Available: {', '.join(g['skill'] for g in all_gaps[:10])}",
        }

    example_ids: list[str] = gap_entry.get("example_ids") or []

    # Fetch the actual listings for those IDs
    all_scored = storage.get_listings(_db(config), limit=500, min_score=0)
    id_set = set(example_ids)
    matched = [r for r in all_scored if r.get("id") in id_set]
    matched.sort(key=lambda r: -(r.get("fit_score") or 0))

    rows = [
        {
            "listing_id": r.get("id"),
            "title":      r.get("title"),
            "company":    r.get("company"),
            "score":      r.get("fit_score"),
            "location":   r.get("location"),
            "url":        r.get("url"),
        }
        for r in matched
    ]

    summary = (
        f"Skill '{canon_skill}' blocks {gap_entry['listings_blocked']} listing(s), "
        f"opportunity cost {gap_entry['opportunity_cost']:.2f}. "
        f"Showing {len(rows)} example(s)."
    )
    return {"rows": rows, "summary": summary}


